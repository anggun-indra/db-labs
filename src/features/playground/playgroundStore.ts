import { create } from 'zustand'
import { sqliteService } from '@/lib/sqlite/sqlJsRuntime'
import type { QueryExecutionResult } from '@/lib/sqlite/queryResult'
import { loadDraft, saveDraft } from './domain/draftStorage'
import {
  appendHistory,
  clearHistory,
  loadHistory,
  type QueryHistoryEntry
} from './domain/queryHistory'
import { useProjectDbStore } from '@/stores/projectDbStore'

/**
 * SQL Playground state (Phase 3): editor draft (debounced per-project
 * persistence), execution against the local SQLite service, and history.
 */

export const DRAFT_DEBOUNCE_MS = 500

interface PlaygroundState {
  projectId: string | null
  sql: string
  result: QueryExecutionResult | null
  running: boolean
  history: QueryHistoryEntry[]
  /** Last SQL generated by the visual row editor (teaching visibility). */
  lastMutationSql: string | null

  loadFor(projectId: string): void
  setSql(sql: string): void
  clearEditor(): void
  run(text: string): Promise<QueryExecutionResult>
  recordMutation(sql: string): Promise<QueryExecutionResult>
  clearHistoryEntries(): void
}

let draftTimer: ReturnType<typeof setTimeout> | undefined

export const usePlaygroundStore = create<PlaygroundState>()((set, get) => ({
  projectId: null,
  sql: '',
  result: null,
  running: false,
  history: [],
  lastMutationSql: null,

  loadFor(projectId) {
    if (draftTimer) {
      clearTimeout(draftTimer)
      draftTimer = undefined
    }
    set({
      projectId,
      sql: loadDraft(projectId),
      history: loadHistory(projectId),
      result: null,
      running: false,
      lastMutationSql: null
    })
  },

  setSql(sql) {
    set({ sql })
    const { projectId } = get()
    if (!projectId) return
    if (draftTimer) clearTimeout(draftTimer)
    draftTimer = setTimeout(() => {
      saveDraft(projectId, sql)
      draftTimer = undefined
    }, DRAFT_DEBOUNCE_MS)
  },

  clearEditor() {
    get().setSql('')
  },

  async run(text): Promise<QueryExecutionResult> {
    const { projectId } = get()
    if (!projectId || text.trim().length === 0) {
      const emptyResult: QueryExecutionResult = {
        kind: 'error',
        executionTimeMs: 0,
        error: {
          raw: 'No SQL statement to run.',
          code: 'EMPTY_STATEMENT',
          hint: 'Write a SQL query in the editor or select a table in the data editor.'
        }
      }
      return emptyResult
    }
    set({ running: true })
    const result = await sqliteService.execute(text)
    // Explicit runs should survive immediate navigation/reload: force the
    // debounced byte persist for statements that changed data.
    if (result.kind === 'mutation' || (result.affectedRows ?? 0) > 0) {
      await sqliteService.flush()
    }
    const history = appendHistory(projectId, {
      sql: text,
      ok: result.kind !== 'error',
      executionTimeMs: result.executionTimeMs
    })
    set({ result, running: false, history })
    // Mutations change what the schema explorer / data editor show.
    if (result.kind !== 'error') {
      await useProjectDbStore.getState().refreshSchema(null)
    }
    return result
  },

  async recordMutation(sql): Promise<QueryExecutionResult> {
    set({ lastMutationSql: sql })
    return await get().run(sql)
  },

  clearHistoryEntries() {
    const { projectId } = get()
    if (!projectId) return
    clearHistory(projectId)
    set({ history: [] })
  }
}))
